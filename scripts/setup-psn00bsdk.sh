#!/usr/bin/env bash
# Download and install a prebuilt PSn00bSDK + Nugget toolchain for Linux.
# Copyright (c) 2026 Johannes Brorsson. All Rights Reserved.
#
# Usage:
#   ./scripts/setup-psn00bsdk.sh [install_dir]
# Default install_dir: ./third_party/psn00bsdk
#
# After success, source the printed export lines (or add them to your shell rc).

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
INSTALL_DIR="${1:-${ROOT}/third_party/psn00bsdk}"
RELEASE_TAG="${PSN00BSDK_RELEASE:-v0.24}"
BASE_URL="https://github.com/Lameguy64/PSn00bSDK/releases/download/${RELEASE_TAG}"

SDK_ZIP="PSn00bSDK-${RELEASE_TAG}-linux.zip"
# Historical asset names vary; try common patterns.
SDK_CANDIDATES=(
	"PSn00bSDK-${RELEASE_TAG#v}-linux.zip"
	"PSn00bSDK-${RELEASE_TAG}-linux.zip"
	"psn00bsdk-${RELEASE_TAG}-linux.zip"
)
TC_ZIP="gcc-mipsel-none-elf-12.3.0-linux.zip"

mkdir -p "${INSTALL_DIR}"
TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT

echo "==> Install dir: ${INSTALL_DIR}"
echo "==> Release: ${RELEASE_TAG}"

download() {
	local url="$1"
	local out="$2"
	echo "Downloading ${url}"
	if ! curl -fL --retry 3 --retry-delay 2 -o "${out}" "${url}"; then
		return 1
	fi
}

echo "==> Fetching Nugget GCC toolchain (${TC_ZIP})"
if ! download "${BASE_URL}/${TC_ZIP}" "${TMP}/${TC_ZIP}"; then
	echo "ERROR: failed to download toolchain zip from ${BASE_URL}/${TC_ZIP}" >&2
	echo "Check https://github.com/Lameguy64/PSn00bSDK/releases for current asset names." >&2
	exit 1
fi

echo "==> Extracting toolchain"
unzip -q -o "${TMP}/${TC_ZIP}" -d "${INSTALL_DIR}"

SDK_OK=0
for name in "${SDK_CANDIDATES[@]}"; do
	if download "${BASE_URL}/${name}" "${TMP}/sdk.zip"; then
		SDK_ZIP="${name}"
		SDK_OK=1
		break
	fi
done

if [[ "${SDK_OK}" -ne 1 ]]; then
	echo "ERROR: could not download a PSn00bSDK Linux zip for ${RELEASE_TAG}." >&2
	echo "Tried: ${SDK_CANDIDATES[*]}" >&2
	echo "Install manually from https://github.com/Lameguy64/PSn00bSDK/releases then set:" >&2
	echo "  export PSN00BSDK_LIBS=<install>/lib/libpsn00b" >&2
	echo "  export PATH=<install>/bin:\$PATH" >&2
	exit 1
fi

echo "==> Extracting SDK (${SDK_ZIP})"
unzip -q -o "${TMP}/sdk.zip" -d "${INSTALL_DIR}"

# Locate libpsn00b/cmake/sdk.cmake (nested release folders vary).
LIBS=""
SDK_CMAKE="$(find "${INSTALL_DIR}" -type f -path '*/lib/libpsn00b/cmake/sdk.cmake' 2>/dev/null | head -n 1 || true)"
if [[ -n "${SDK_CMAKE}" ]]; then
	LIBS="$(cd "$(dirname "${SDK_CMAKE}")/.." && pwd)"
fi

BIN_DIR=""
GCC_BIN="$(find "${INSTALL_DIR}" -type f -name mipsel-none-elf-gcc 2>/dev/null | head -n 1 || true)"
if [[ -n "${GCC_BIN}" ]]; then
	BIN_DIR="$(cd "$(dirname "${GCC_BIN}")" && pwd)"
fi
# Also put SDK tools (elf2x, mkpsxiso) on PATH when present.
SDK_BIN="$(find "${INSTALL_DIR}" -type f -name mkpsxiso 2>/dev/null | head -n 1 || true)"
if [[ -n "${SDK_BIN}" ]]; then
	SDK_BIN_DIR="$(cd "$(dirname "${SDK_BIN}")" && pwd)"
	if [[ -n "${BIN_DIR}" && "${BIN_DIR}" != "${SDK_BIN_DIR}" ]]; then
		BIN_DIR="${BIN_DIR}:${SDK_BIN_DIR}"
	else
		BIN_DIR="${SDK_BIN_DIR}"
	fi
fi

if [[ -z "${LIBS}" || ! -f "${LIBS}/cmake/sdk.cmake" ]]; then
	echo "ERROR: could not find lib/libpsn00b/cmake/sdk.cmake under ${INSTALL_DIR}" >&2
	find "${INSTALL_DIR}" -maxdepth 5 -type d | head -n 60 >&2 || true
	exit 1
fi

ENV_FILE="${INSTALL_DIR}/env.sh"
cat > "${ENV_FILE}" <<EOF
# Generated by scripts/setup-psn00bsdk.sh
export PSN00BSDK_LIBS="${LIBS}"
export PATH="${BIN_DIR}:\${PATH}"
EOF

echo
echo "OK. Activate with:"
echo "  source ${ENV_FILE}"
echo "Then build:"
echo "  make"
echo
echo "Note: DuckStation + a PS1 BIOS on your machine are required to run the .cue."
